static const char* g_table[LANG_COUNT][S_COUNT];

template <size_t N>
static void Fill(int l, const Entry (&e)[N])
{
    for (size_t i = 0; i < N; i++) g_table[l][e[i].key] = e[i].text;
}

void Init()
{
    Fill(LANG_TR, kTR);
    Fill(LANG_EN, kEN);
    Fill(LANG_DE, kDE);
    Fill(LANG_FR, kFR);
    Fill(LANG_ES, kES);
    Fill(LANG_RU, kRU);
    Fill(LANG_PT, kPT);
}

const char* T(Str s)
{
    int l = (current >= 0 && current < LANG_COUNT) ? current : LANG_EN;
    if (const char* t = g_table[l][s]) return t;
    if (const char* t = g_table[LANG_EN][s]) return t;
    return "?";
}

const char* NativeName(int l)
{
    static const char* names[LANG_COUNT] = { "Türkçe", "English", "Deutsch", "Français", "Español", "Русский", "Português" };
    return (l >= 0 && l < LANG_COUNT) ? names[l] : "";
}

const char* Code(int l)
{
    static const char* codes[LANG_COUNT] = { "TR", "EN", "DE", "FR", "ES", "RU", "PT" };
    return (l >= 0 && l < LANG_COUNT) ? codes[l] : "";
}

